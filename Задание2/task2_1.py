def is_palindrome(s):
    """
    Проверяет, является ли строка палиндромом.
    
    Аргументы:
    s (str): Строка для проверки
    
    Возвращает:
    bool: True, если строка палиндром, иначе False
    """
    # Убираем пробелы и приводим к нижнему регистру для корректного сравнения
    cleaned = ''.join(c.lower() for c in s if c.isalnum())
    
    # Сравниваем строку с ее обратной версией
    return cleaned == cleaned[::-1]


# Тестирование функции
if __name__ == "__main__":
    # Тестовые примеры
    test_strings = [
        "А роза упала на лапу Азора",  # Русский палиндром
        "racecar",                     # Английский палиндром
        "hello",                       # Не палиндром
        "12321",                       # Числовой палиндром
        "Мадам",                       # Палиндром
    ]
    
    for test in test_strings:
        result = is_palindrome(test)
        print(f"'{test}' -> {'Палиндром' if result else 'Не палиндром'}")